"""公的な項目辞書と規則コードだけから、通信不要の共有データを生成する。"""
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / 'jtools'


def build():
    raw = json.loads((ROOT / 'materials/jp_municipal_fields.json').read_text(encoding='utf-8'))
    rows, seen = [], set()
    for row in raw:
        item = [row.get(k, '') for k in ('dataset', 'name', 'name_en', 'format')]
        if tuple(item) not in seen:
            seen.add(tuple(item)); rows.append(item)
    write('std_fields_data', {'source': 'materials/jp_municipal_fields.json', 'fields': rows})
    # 選んだ定数の代入だけを評価。答え・裁定・教材をimport/参照しない。
    selected = {'READING', 'LIC', 'INST_V', 'INST_C', 'LOC_C', 'USE_LOC', 'ORG_V', 'PLACE_V', 'KINDS', 'FIXED', 'HEAD', 'NOT'}
    scope = {'re': re}
    for file in ('pool_v24.py', 'collect.py'):
        tree = ast.parse((ROOT / 'research/facility_names' / file).read_text(encoding='utf-8'))
        for node in tree.body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and node.targets[0].id in selected:
                exec(compile(ast.Module(body=[node], type_ignores=[]), file, 'exec'), scope)
    rules = {}
    for name in sorted(selected - {'KINDS', 'FIXED'}):
        pattern = scope[name]
        rules[name] = [pattern.pattern, bool(pattern.flags & re.I)]
    rules['KINDS'] = scope['KINDS']
    rules['FIXED'] = [[p.pattern, label, reason] for p, label, reason in scope['FIXED']]
    write('facility_rules', rules)


def write(name, data):
    text = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    (HERE / (name + '.json')).write_text(text + '\n', encoding='utf-8')
    # JSONを埋め込んだES module。ブラウザからfetch/JSON importをせずに使える。
    (HERE / (name + '.mjs')).write_text('// Generated by jtools/build_data.py\nexport default ' + text + ';\n', encoding='utf-8')


if __name__ == '__main__':
    build()
